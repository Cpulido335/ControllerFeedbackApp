struct fontMapping* getGlyphFromFontMap(const char asciiChar, struct fontMapping fontMap[]) //lets return a pointer to it instead
{
    for(int i = 0; i < FONT_MAP_LENGTH; i++) //hardcode
    {
        if(fontMap[i].asciiChar == asciiChar)
            return &fontMap[i];
    }
    //error 
    printf("Error: ascii character '%c' not found in font map!\n", asciiChar);
    return NULL;
}

